SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)

directories_to_update = [
    os.path.join(PROJECT_ROOT, 'data'),
    os.path.join(PROJECT_ROOT, 'web-simulator')
]

json_path = os.path.join(directories_to_update[0], 'categories_files.json')
with open(json_path, 'r', encoding='utf-8') as f:
    categories = json.load(f)

new_categories = {}
translate_map = {}

def get_trans(ar_word):
    if ar_word in translations:
        return translations[ar_word]
    if ar_word.endswith(' '):
        ar_word = ar_word.strip()
        if ar_word in translations:
            return translations[ar_word] + '_sp'
    return None

import uuid

# First pass: map exactly what we have, fallback to uuid if not found
for ar_cat, ar_words in categories.items():
    en_cat = get_trans(ar_cat) or f"Cat_{uuid.uuid4().hex[:4]}"
    en_cat = en_cat.strip()
    new_categories[en_cat] = []
    
    for ar_word in ar_words:
        if ar_word.isdigit():
            en_word = ar_word
        else:
            en_word = get_trans(ar_word)
            if not en_word:
                en_word = f"word_{uuid.uuid4().hex[:6]}"
                
        translate_map[ar_word] = en_word
        new_categories[en_cat].append(en_word)

def rename_sigml_files(sigml_dir):
    if not os.path.exists(sigml_dir):
        return
    for ar_filename in os.listdir(sigml_dir):
        if not ar_filename.endswith('.sigml'):
            continue
        base = ar_filename[:-6]
        if base in translate_map:
            en_word = translate_map[base]
            if base != en_word:
                src = os.path.join(sigml_dir, ar_filename)
                dst = os.path.join(sigml_dir, f"{en_word}.sigml")
                shutil.move(src, dst)
        else:
            # Maybe the word was not in json but exists as a file, let's translate if in dict
            if base in translations:
                src = os.path.join(sigml_dir, ar_filename)
                dst = os.path.join(sigml_dir, f"{translations[base]}.sigml")
                shutil.move(src, dst)

for base_dir in directories_to_update:
    sigml_dir = os.path.join(base_dir, 'sigml')
    rename_sigml_files(sigml_dir)
    out_json = os.path.join(base_dir, 'categories_files.json')
    with open(out_json, 'w', encoding='utf-8') as f:
        json.dump(new_categories, f, indent=4, ensure_ascii=False)

print("Mapping generated offline applied successfully.")
